/* ---------------------------------------------------------------- 排版助手 */

const h2 = (text, id) => el('h2', { class: 'doc-h2', id }, text);
const h3 = (text) => el('h3', { class: 'doc-h3' }, text);
const p = (...children) => el('p', { class: 'doc-p' }, ...children);
const ul = (items) => el('ul', { class: 'doc-ul' }, ...items.map((t) => el('li', {}, t)));
const b = (t) => el('b', {}, t);
const code = (t) => el('code', { class: 'doc-inline-code' }, t);
const link = (href, text) => el('a', { href, target: '_blank', rel: 'noreferrer' }, text);

function block(codeText, lang = '') {
  const pre = el('pre', { class: 'doc-code' }, el('code', {}, codeText));
  const copy = el(
    'button',
    {
      class: 'doc-copy',
      type: 'button',
      onclick: async () => {
        try {
          await navigator.clipboard.writeText(codeText);
          copy.textContent = '已复制';
          setTimeout(() => (copy.textContent = '复制'), 1400);
        } catch {
          toast('复制失败，请手动选中', 'error');
        }
      },
    },
    '复制',
  );
  return el('div', { class: 'doc-code-wrap' }, lang ? el('div', { class: 'doc-code-lang' }, lang) : null, copy, pre);
}

function table(headers, rows) {
  return el(
    'div',
    { class: 'doc-table-wrap' },
    el(
      'table',
      { class: 'doc-table' },
      el('thead', {}, el('tr', {}, ...headers.map((t) => el('th', {}, t)))),
      el(
        'tbody',
        {},
        ...rows.map((row) => el('tr', {}, ...row.map((cell) => el('td', {}, cell)))),
      ),
    ),
  );
}

const callout = (kind, title, body) =>
  el(
    'div',
    { class: `doc-callout ${kind}` },
    el('div', { class: 'doc-callout-title' }, title),
    el('div', { class: 'doc-callout-body' }, body),
  );

