export default {
  async render(host, ctx) {
    const navItems = new Map();
    const nav = el('nav', { class: 'doc-nav' });
    for (const s of SECTIONS) {
      const item = el(
        'button',
        {
          class: 'doc-nav-item',
          type: 'button',
          onclick: () => {
            document.getElementById(s.id)?.scrollIntoView({ behavior: 'smooth', block: 'start' });
          },
        },
        s.title,
      );
      navItems.set(s.id, item);
      nav.append(item);
    }

    const body = el('div', { class: 'doc-body' });
    for (const s of SECTIONS) {
      for (const node of CONTENT[s.id]()) body.append(node);
      body.append(el('div', { class: 'doc-divider' }));
    }

    const scroller = el(
      'div',
      { class: 'doc-scroll' },
      /* 开头：图标 + 名称 + 版本号 + 简介 */
      el(
        'header',
        { class: 'doc-hero' },
        el(
          'div',
          { class: 'doc-hero-mark' },
          el(
            'svg',
            { viewBox: '0 0 32 32', width: '56', height: '56', 'aria-hidden': 'true' },
            el('rect', { width: '32', height: '32', rx: '8', fill: 'url(#qlGrad)' }),
            el('path', {
              d: 'M3.5 15.2H9.2L11.8 9.8L15.1 20.6L17.2 13.6L19.2 15.2H28.5',
              fill: 'none',
              stroke: '#fff',
              'stroke-width': '2.3',
              'stroke-linecap': 'round',
              'stroke-linejoin': 'round',
            }),
            el(
              'text',
              {
                x: '16',
                y: '28.2',
                'text-anchor': 'middle',
                'font-family': "'Segoe UI','Helvetica Neue',Arial,system-ui,sans-serif",
                'font-size': '8.6',
                'font-weight': '700',
                fill: '#fff',
              },
              'Link',
            ),
          ),
        ),
        el(
          'div',
          { class: 'doc-hero-text' },
          el('h1', { class: 'doc-hero-title' }, 'Q-Link', el('span', { class: 'doc-hero-version' }, VERSION)),
          el(
            'p',
            { class: 'doc-hero-desc' },
            'QQ 机器人控制台。扫码接入 QQ 开放平台，在一个界面里调教机器人的',
            el('b', {}, '人设、记忆、关键词、名单表、违禁词、表情包与梗知识'),
            '，改完即时生效；支持同时管理多台互相独立的机器人。',
          ),
        ),
      ),
      body,
    );

    mount(
      host,
      el('div', { class: 'page-head' }, el('h1', {}, '文档')),
      el('div', { class: 'doc-layout' }, nav, scroller),
    );

    /* 滚动时高亮当前章节。
       注意：真正滚动的是外层的内容区 #main，不是 .doc-scroll（它没有自己的滚动条），
       所以监听对象必须是 #main，否则高亮会一直停在某个固定项上。 */
    const scrollRoot = document.getElementById('main') || window;
    const highlight = () => {
      const rootTop = scrollRoot === window ? 0 : scrollRoot.getBoundingClientRect().top;
      let activeId = SECTIONS[0].id;
      for (const s of SECTIONS) {
        const node = document.getElementById(s.id);
        if (!node) continue;
        // 取"最后一个已经滚过容器顶部（留 80px 余量）"的章节
        if (node.getBoundingClientRect().top - rootTop <= 80) activeId = s.id;
      }
      // 已经滚到底部时，直接高亮最后一节
      if (scrollRoot !== window && scrollRoot.scrollTop + scrollRoot.clientHeight >= scrollRoot.scrollHeight - 8) {
        activeId = SECTIONS[SECTIONS.length - 1].id;
      }
      for (const [id, item] of navItems) item.classList.toggle('active', id === activeId);
    };

    scrollRoot.addEventListener('scroll', highlight, { passive: true });
    window.addEventListener('resize', highlight);
    highlight();

    return () => {
      scrollRoot.removeEventListener('scroll', highlight);
      window.removeEventListener('resize', highlight);
    };
  },
};
